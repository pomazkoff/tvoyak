/**
 * Особые темы: у каждой — бриф для генератора, правило для LLM-рецензентов
 * и (если нужно) подсказка LLM-судье, как принимать ответ. Генератор
 * (scripts/grow-bank.ts, регулярное пополнение по пн/пт) и ревью
 * (pipeline.reviewItem) берут правила отсюда по названию темы.
 */
export type SpecialCategory = {
  category: string;
  /** О чём тема — уходит генератору как brief. */
  brief: string;
  /** Формат вопроса для генератора (дописывается к общему заданию). */
  format: string;
  /** Что дополнительно проверяют рецензенты (fact/freshness/difficulty). */
  review: string;
  /** Подсказка судье: как засчитывать ответ. */
  judge?: string;
  /** Медийная тема: text-генератор её не пополняет, нужен свой источник. */
  media?: "music" | "video";
};

