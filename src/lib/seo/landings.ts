export const LANDINGS = [corporateLanding, birthdayLanding, tvLanding] as const;

export const LANDING_PATHS = LANDINGS.map((page) => page.path);

export function landingHeadline(page: LandingPage): string {
  return page.h1.join(" ");
}

export function landingMetadata(page: LandingPage): Metadata {
  return {
    title: { absolute: page.title },
    description: page.description,
    alternates: { canonical: page.path },
    openGraph: {
      type: "website",
      locale: "ru_RU",
      url: page.path,
      siteName: SITE_NAME,
      title: page.ogTitle,
      description: page.ogDescription,
    },
    twitter: {
      card: "summary_large_image",
      title: page.ogTitle,
      description: page.ogDescription,
    },
  };
}

export function landingJsonLd(page: LandingPage) {
  const url = `${SITE_URL}${page.path}`;
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "WebPage",
        "@id": `${url}#webpage`,
        url,
        name: page.title,
        headline: landingHeadline(page),
        description: page.description,
        inLanguage: "ru-RU",
        isPartOf: {
          "@type": "WebSite",
          name: SITE_NAME,
          url: `${SITE_URL}/`,
        },
      },
      {
        "@type": "FAQPage",
        "@id": `${url}#faq`,
        url,
        inLanguage: "ru-RU",
        mainEntity: page.faq.map((item) => ({
          "@type": "Question",
          name: item.question,
          acceptedAnswer: { "@type": "Answer", text: item.answer },
        })),
      },
    ],
  };
}

/** Как в документации Next: `<` в JSON-LD не должен оборвать script. */
export function jsonLdScript(data: unknown): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}

const FORBIDDEN = [
  "своя игра",
  "что? где? когда",
  "что где когда",
  "jackbox",
  "kahoot",
  "quizizz",
  "quizziz",
  "брейн-ринг",
  "брейн ринг",
  "слабое звено",
  "поле чудес",
  "сто к одному",
  "кто хочет стать миллионером",
  "jeopardy",
];

export function forbiddenMentions(text: string): string[] {
  const lower = text.toLowerCase();
  return FORBIDDEN.filter((phrase) => lower.includes(phrase));
}
