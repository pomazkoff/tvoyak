-- Первая волна «Детского рисунка» — на самые дешёвые номиналы:
-- 100, два самых трудных («Движение вверх», «Звёздные войны») — 200.
-- Только update банка: сыгранные и идущие комнаты не трогаем.
update public.question_bank
set value = case when answer in ('Движение вверх', 'Звёздные войны') then 200 else 100 end
where picture = 'kids'
  and prompt ~ '^Детский рисунок № ([1-9]|1[0-9]|2[0-5]): ';
